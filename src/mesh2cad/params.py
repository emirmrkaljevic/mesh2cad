"""List and edit named parameters in a script mesh2cad generated.

The editable numbers are the assignments between the ``parameters`` and
``model`` markers. A change replaces that numeric token and leaves every
other byte alone. The script is then run with the same backend that already
renders it: CadQuery in-process, or the ``openscad`` / ``freecadcmd`` program
when it is on ``PATH``.

Only those generated scripts are accepted. Values passed in are parsed as
numbers and written back as numeric literals. They are not evaluated as code.
"""
from __future__ import annotations

import ast
import math
import os
import re
import shutil
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

_HEADER = "generated by mesh2cad"
_MARKERS = (
    ("# --- parameters ---", "# --- model ---"),
    ("// --- parameters ---", "// --- model ---"),
)
_ASSIGN = re.compile(r"^[ \t]*(?P<name>[A-Za-z_][A-Za-z0-9_]*)[ \t]*=[ \t]*")
_NUMBER = re.compile(r"[+-]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?")
_HOLE_D = re.compile(r"hole_(\d+)_d\Z")
_MEMBER_HOLE_D = re.compile(r"(base_hole|leg_hole)_(\d+)_d\Z")
_EXTRUDE_LEN = re.compile(r"extrude_([xyz])(\d*)_len\Z")
_FACE = {"X": "yz", "Y": "xz", "Z": "xy"}
_PLANE_AXIS = {"XY": "Z", "XZ": "Y", "YZ": "X"}
# A generated hole can sit a few tenths of a millimetre inside a fitted wall.
# Past this, the circle is no longer in the wall.
_BREAKOUT_MM = 0.3


class ParamError(ValueError):
    """The script or the requested edit cannot be applied."""

    def __init__(self, message: str, valid: list[str] | None = None):
        super().__init__(message)
        self.valid = list(valid or [])


class GeometryError(ParamError):
    """The edit would not leave one valid solid."""


@dataclass
class Parameter:
    name: str
    value: object
    kind: str
    unit: str | None
    note: str
    span: tuple[int, int]


@dataclass
class Script:
    path: str
    text: str
    backend: str
    parameters: list[Parameter]
    model: str = ""
    _index: dict[str, Parameter] = field(default_factory=dict)

    def __post_init__(self) -> None:
        self._index = {p.name: p for p in self.parameters}

    def get(self, name: str) -> Parameter | None:
        return self._index.get(name)

    def scalars(self) -> dict[str, float]:
        return {p.name: float(p.value) for p in self.parameters if isinstance(p.value, float)}

    def notes(self) -> dict[str, str]:
        return {p.name: p.note for p in self.parameters}


@dataclass
class _Extrusion:
    axis: str
    origin: float
    length: float
    outline: list
    plane: str


def format_number(value: float) -> str:
    """A short decimal literal both Python and OpenSCAD accept."""
    value = float(value)
    if not math.isfinite(value):
        raise ParamError("value is not a finite number")
    rounded = round(value, 8)
    if abs(rounded) < 5e-9:
        return "0.0"
    text = f"{rounded:.8f}".rstrip("0").rstrip(".")
    if "." not in text:
        text += ".0"
    return text


def list_parameters(path: str) -> dict:
    """Read the editable parameters of a generated script."""
    script = load(path)
    return {
        "script_path": str(Path(path)),
        "backend": script.backend,
        "parameters": [_public(p) for p in script.parameters],
    }


def check_edit(path: str, changes: dict) -> list[dict]:
    """Resolve ``changes`` and apply the static geometry checks.

    Does not render and does not write. A numeric value replaces the parameter.
    A string that starts with ``+`` or ``-`` is a delta.
    """
    script = load(path)
    if not changes:
        raise ParamError("pass at least one parameter to change")
    resolved = _resolve_changes(script, changes)
    _check_geometry(script, resolved)
    return [_change_row(script, name, new) for name, new in resolved.items()]


def edit_script(path: str, changes: dict, output_path: str | None = None, *,
                in_place: bool = False, output_script: str | None = None,
                default_render: bool = False) -> dict:
    """Rewrite ``changes`` into ``path``, re-render when the backend exists, and write.

    A numeric change is absolute. A string that starts with ``+`` or ``-`` is
    added to the current value. Nothing is written when the edit is refused.
    """
    script = load(path)
    if not changes:
        raise ParamError("pass at least one parameter to change")
    resolved = _resolve_changes(script, changes)
    _check_geometry(script, resolved)
    new_text = _rewrite(script, resolved)
    backend = script.backend
    dest = output_path
    if dest is None and default_render and _backend_available(backend):
        dest = str(_default_render_path(path, backend))
    if dest is not None:
        _check_suffix(backend, dest)
        if not _backend_available(backend):
            raise ParamError(_missing_backend(backend) + " Nothing was written.")
    report = {
        "script_path": str(Path(path)),
        "backend": backend,
        "changes": [_change_row(script, name, new) for name, new in resolved.items()],
        "script_written": None,
        "rendered": False,
        "output_path": None,
        "valid_solid": None,
        "before": None,
        "after": None,
        "delta": None,
        "warnings": [],
    }
    if _backend_available(backend):
        with tempfile.TemporaryDirectory(prefix="mesh2cad-edit-") as tmp:
            work = Path(tmp)
            before, _exported_before = _measure(script.text, backend, work / "before", None, "the script on disk")
            export = _export_kind(backend, dest)
            after, exported = _measure(new_text, backend, work / "after", export, "the edit")
            if dest is not None and exported is not None:
                out = Path(dest)
                out.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(exported, out)
                report["output_path"] = str(out)
        report["rendered"] = True
        report["valid_solid"] = True
        report["before"] = before
        report["after"] = after
        report["delta"] = {
            "volume": after["volume"] - before["volume"],
            "bbox_min": [a - b for a, b in zip(after["bbox_min"], before["bbox_min"])],
            "bbox_max": [a - b for a, b in zip(after["bbox_max"], before["bbox_max"])],
        }
    else:
        report["warnings"].append(_missing_backend(backend))
    written = _script_destination(path, in_place, output_script)
    if written is not None:
        _atomic_write(written, new_text)
        report["script_written"] = str(written)
    return report


def format_parameters(info: dict) -> str:
    rows = []
    for p in info["parameters"]:
        rows.append((p["name"], _display_value(p), p["kind"], p["unit"] or "", p.get("note") or ""))
    header = ("name", "value", "kind", "unit", "note")
    widths = [len(h) for h in header]
    for row in rows:
        for i, cell in enumerate(row):
            widths[i] = max(widths[i], len(cell))
    lines = ["  ".join(h.ljust(widths[i]) for i, h in enumerate(header)).rstrip()]
    for row in rows:
        lines.append("  ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)).rstrip())
    return "\n".join(lines) + "\n"


def format_report(info: dict) -> str:
    lines = []
    for row in info["changes"]:
        unit = f", {row['unit']}" if row.get("unit") else ""
        lines.append(
            f"{row['name']}: {format_number(row['old'])} -> {format_number(row['new'])} "
            f"({row['kind']}{unit})"
        )
    if info.get("rendered"):
        before, after = info["before"], info["after"]
        delta = info["delta"]["volume"]
        sign = "+" if delta >= 0 else ""
        lines.append(
            f"volume: {before['volume']:.2f} -> {after['volume']:.2f} mm^3 "
            f"(delta {sign}{delta:.2f})"
        )
        lines.append(f"bbox min: {_fmt_xyz(before['bbox_min'])} -> {_fmt_xyz(after['bbox_min'])}")
        lines.append(f"bbox max: {_fmt_xyz(before['bbox_max'])} -> {_fmt_xyz(after['bbox_max'])}")
        lines.append("valid solid: yes" if info["valid_solid"] else "valid solid: no")
    for warning in info.get("warnings") or []:
        lines.append(f"warning: {warning}")
    if info.get("script_written"):
        lines.append(f"wrote script {info['script_written']}")
    else:
        lines.append("script unchanged on disk")
    if info.get("output_path"):
        lines.append(f"wrote {info['output_path']}")
    return "\n".join(lines) + "\n"


def load(path: str) -> Script:
    file = Path(path)
    if not file.is_file():
        raise ParamError(f"no such file: {path}")
    text = file.read_text(encoding="utf-8")
    if _HEADER not in text:
        raise ParamError(
            "this is not a script mesh2cad generated. "
            "params and edit only change scripts mesh2cad wrote."
        )
    content_start, content_end, _start = _parameter_span(text)
    backend = _backend(path, text)
    model = text[content_end:]
    parameters = _parse_parameters(text, content_start, content_end)
    if not parameters:
        raise ParamError("the parameter block is empty")
    return Script(str(file), text, backend, parameters, model)


def _public(p: Parameter) -> dict:
    row = {
        "name": p.name,
        "value": p.value,
        "kind": p.kind,
        "unit": p.unit,
        "note": p.note,
    }
    if p.kind == "points" and isinstance(p.value, list):
        row["count"] = len(p.value)
    return row


def _display_value(p: dict) -> str:
    if p["kind"] == "points":
        return f"{p.get('count', len(p['value']))} points"
    if isinstance(p["value"], float):
        return format_number(p["value"])
    if isinstance(p["value"], list):
        return "[" + ", ".join(str(v) for v in p["value"]) + "]"
    return str(p["value"])


def _fmt_xyz(values) -> str:
    return "[" + ", ".join(f"{float(v):.3f}" for v in values) + "]"


def _parameter_span(text: str) -> tuple[int, int, str]:
    for start, end in _MARKERS:
        i = text.find(start)
        if i < 0:
            continue
        j = text.find(end, i + len(start))
        if j < 0:
            continue
        line_end = text.find("\n", i)
        content_start = i + len(start) if line_end < 0 or line_end > j else line_end + 1
        return content_start, j, start
    raise ParamError(
        "this is not a script mesh2cad generated "
        "(missing the parameter block). params and edit only change those scripts."
    )


def _backend(path: str, text: str) -> str:
    low = text.lower()
    suf = Path(path).suffix.lower()
    if suf == ".scad" or "openscad model generated by mesh2cad" in low:
        return "openscad"
    if suf == ".fcmacro" or "freecad model generated by mesh2cad" in low:
        return "freecad"
    if suf == ".py" or "cadquery model generated by mesh2cad" in low:
        return "cadquery"
    raise ParamError("could not tell whether this script is CadQuery, OpenSCAD, or FreeCAD")


def _parse_parameters(text: str, content_start: int, content_end: int) -> list[Parameter]:
    params: list[Parameter] = []
    seen: set[str] = set()
    pending = ""
    i = content_start
    while i < content_end:
        line_end = text.find("\n", i, content_end)
        if line_end < 0:
            line_end = content_end
        raw = text[i:line_end]
        line = raw[:-1] if raw.endswith("\r") else raw
        stripped = line.strip()
        if not stripped:
            pending = ""
            i = line_end + 1 if line_end < content_end else content_end
            continue
        if stripped.startswith("/*") and "*/" in stripped:
            pending = ""
            i = line_end + 1 if line_end < content_end else content_end
            continue
        if stripped.startswith("//"):
            pending = stripped[2:].strip()
            i = line_end + 1 if line_end < content_end else content_end
            continue
        if stripped.startswith("#"):
            pending = stripped[1:].strip()
            i = line_end + 1 if line_end < content_end else content_end
            continue
        matched = _ASSIGN.match(line)
        if not matched:
            i = line_end + 1 if line_end < content_end else content_end
            continue
        name = matched.group("name")
        if name in seen:
            raise ParamError(f"parameter {name} is assigned more than once")
        seen.add(name)
        try:
            value, span, consumed = _read_value(text, i + matched.end(), content_end)
        except ParamError as exc:
            raise ParamError(f"could not read {name}: {exc}") from exc
        trailing = _trailing_note(text, span[1], line_end) if consumed <= line_end else ""
        note = trailing or pending
        kind, unit = _classify(name, note, value)
        params.append(Parameter(name, value, kind, unit, note, span))
        pending = ""
        if consumed <= line_end:
            i = line_end + 1 if line_end < content_end else content_end
        else:
            nl = text.find("\n", consumed, content_end)
            i = content_end if nl < 0 else nl + 1
    return params


def _read_value(text: str, i: int, limit: int):
    while i < limit and text[i] in " \t":
        i += 1
    if i >= limit:
        raise ParamError("missing value")
    if text[i] in "[(":
        token, end = _read_brackets(text, i, limit)
        try:
            value = ast.literal_eval(token)
        except (SyntaxError, ValueError) as exc:
            raise ParamError("value is not a literal") from exc
        return _normalize(value), (i, end), end
    matched = _NUMBER.match(text, i)
    if not matched or matched.start() != i:
        raise ParamError("value is not a number")
    return float(matched.group(0)), (matched.start(), matched.end()), matched.end()


def _read_brackets(text: str, i: int, limit: int) -> tuple[str, int]:
    pairs = {"[": "]", "(": ")"}
    stack = []
    start = i
    while i < limit:
        char = text[i]
        if char in pairs:
            stack.append(pairs[char])
        elif char in ")]":
            if not stack or char != stack[-1]:
                raise ParamError("unbalanced brackets")
            stack.pop()
            if not stack:
                return text[start:i + 1], i + 1
        i += 1
    raise ParamError("unclosed brackets")


def _normalize(value):
    if isinstance(value, tuple):
        value = list(value)
    if not isinstance(value, list):
        return value
    if not value:
        return []
    if isinstance(value[0], (list, tuple)):
        return [[float(x) for x in row[:2]] for row in value]
    if isinstance(value[0], (int, float)) and not isinstance(value[0], bool):
        out = []
        for item in value:
            number = float(item)
            out.append(int(number) if number.is_integer() else number)
        return out
    return value


def _trailing_note(text: str, span_end: int, line_end: int) -> str:
    if span_end > line_end:
        return ""
    tail = text[span_end:line_end].strip()
    if tail.startswith(";"):
        tail = tail[1:].strip()
    if tail.startswith("//"):
        comment = tail[2:].strip()
    elif tail.startswith("#"):
        comment = tail[1:].strip()
    else:
        return ""
    if comment.startswith("["):
        return ""
    return comment


def _classify(name: str, note: str, value) -> tuple[str, str | None]:
    """Kind comes from the parameter name. The note is only a fallback.

    ``base_z0`` is "bottom face height" in the comment, and that word must not
    turn a position that is allowed to be negative into a length.
    """
    if isinstance(value, list) and value and isinstance(value[0], list):
        return "points", None
    if isinstance(value, list):
        return "indices", None
    if not isinstance(value, float):
        return "value", None
    text = note.lower()
    if name.startswith("clip_") and name.endswith(("_x", "_y", "_z")):
        return "normal", None
    if name.startswith("clip_") and name.endswith("_d") or "plane:" in text:
        return "offset", "mm"
    if "angle" in name or name.endswith("_deg"):
        return "angle", "deg"
    if (name in ("base_cx", "base_cy", "base_z0") or name.endswith("_0")
            or re.fullmatch(r"(?:base_hole|leg_hole|hole|boss|pad|cone)_\d+_[xyz]", name)
            or re.fullmatch(r"hole_\d+_[xyz][01]", name)):
        return "position", "mm"
    if name.endswith("_depth"):
        return "depth", "mm"
    if name.endswith("_d"):
        return "diameter", "mm"
    if (re.fullmatch(r"boss_\d+_fillet", name) or name.endswith(("_r", "_r0", "_r1"))
            or name == "fillet_r"):
        return "radius", "mm"
    if (name.endswith("_len") or name in ("base_x", "base_y", "base_t") or name.endswith("_h")
            or "chamfer" in name or name.endswith(("_w", "_l"))):
        return "length", "mm"
    if "diameter" in text:
        return "diameter", "mm"
    if "radius" in text:
        return "radius", "mm"
    if "depth" in text:
        return "depth", "mm"
    if "angle" in text or "degree" in text:
        return "angle", "deg"
    if "length" in text or "thickness" in text:
        return "length", "mm"
    return "number", "mm"


def _resolve_changes(script: Script, changes: dict) -> dict[str, float]:
    if not isinstance(changes, dict):
        raise ParamError("changes must be a mapping of parameter name to value")
    resolved: dict[str, float] = {}
    valid = [p.name for p in script.parameters]
    numeric = [p.name for p in script.parameters if isinstance(p.value, float)]
    for name, raw in changes.items():
        if not isinstance(name, str) or not name.isidentifier():
            raise ParamError(f"not a parameter name: {name!r}. Valid parameters: {', '.join(valid)}", valid)
        param = script.get(name)
        if param is None:
            raise ParamError(f"unknown parameter {name!r}. Valid parameters: {', '.join(valid)}", valid)
        if not isinstance(param.value, float):
            kind = "point list" if param.kind == "points" else param.kind
            count = f" ({len(param.value)} points)" if param.kind == "points" else ""
            raise ParamError(
                f"{name} is a {kind}{count}, not a single number. "
                f"Numeric parameters: {', '.join(numeric)}",
                numeric,
            )
        resolved[name] = _resolve_value(name, param.value, raw)
    return resolved


def _resolve_value(name: str, old: float, raw) -> float:
    if isinstance(raw, bool) or raw is None:
        raise ParamError(f"{name} needs a number, got {raw!r}")
    if isinstance(raw, (int, float)):
        value = float(raw)
    else:
        text = str(raw).strip().replace(" ", "")
        if not text:
            raise ParamError(f"{name} needs a number")
        try:
            number = float(text)
        except ValueError as exc:
            raise ParamError(f"{name}={text!r} is not a number") from exc
        # A leading sign is a delta: base_x=+2 adds 2, base_x=-1 subtracts 1.
        value = old + number if text[0] in "+-" else number
    if not math.isfinite(value) or abs(value) > 1e5:
        raise ParamError(f"{name}={value} is outside the range mesh2cad will apply (finite, at most 100000)")
    return value


def _rewrite(script: Script, resolved: dict[str, float]) -> str:
    text = script.text
    pieces = []
    cursor = 0
    for param in script.parameters:
        if param.name not in resolved:
            continue
        new = resolved[param.name]
        if abs(new - float(param.value)) <= 1e-9:
            continue
        start, end = param.span
        pieces.append(text[cursor:start])
        pieces.append(format_number(new))
        cursor = end
    pieces.append(text[cursor:])
    return "".join(pieces)


def _change_row(script: Script, name: str, new: float) -> dict:
    param = script.get(name)
    assert param is not None
    return {
        "name": name,
        "old": float(param.value),
        "new": float(new),
        "kind": param.kind,
        "unit": param.unit,
    }


def _check_geometry(script: Script, resolved: dict[str, float]) -> None:
    scalars = script.scalars()
    scalars.update(resolved)
    notes = script.notes()
    for name, value in scalars.items():
        param = script.get(name)
        if param is None or not isinstance(param.value, float):
            continue
        _check_scalar(name, value, param.kind, scalars)
    _check_features(scalars)
    solids, mode = _solids(script, scalars)
    if solids:
        _check_holes(scalars, notes, solids, mode)


def _check_scalar(name: str, value: float, kind: str, scalars: dict[str, float]) -> None:
    if kind in ("length", "depth", "diameter") or (kind == "radius" and not name.endswith("_r1")):
        if value <= 0:
            raise GeometryError(f"{name}={format_number(value)} must be greater than 0")
    if kind == "radius" and name.endswith("_r1") and value < 0:
        raise GeometryError(f"{name}={format_number(value)} must not be negative")
    if kind == "angle":
        if name.endswith("_csk_angle") or "csk_angle" in name:
            if not 1.0 < value < 179.0:
                raise GeometryError(f"{name}={format_number(value)} is not a usable countersink angle (degrees)")
        elif value < -180.0 or value > 180.0:
            raise GeometryError(f"{name}={format_number(value)} is outside -180 to 180 degrees")
    _check_boss(name, value, scalars)


def _check_boss(name: str, value: float, scalars: dict[str, float]) -> None:
    fillet = re.fullmatch(r"boss_(\d+)_fillet", name)
    if fillet:
        height = scalars.get(f"boss_{fillet.group(1)}_h")
        if height is not None and value >= height - 1e-9:
            raise GeometryError(
                f"{name}={format_number(value)} is at least the boss height "
                f"({format_number(height)} mm)"
            )
        return
    matched = re.fullmatch(r"boss_(\d+)_(chamfer|chamfer_h|chamfer_w|draft_deg)", name)
    if not matched:
        return
    idx, suffix = matched.group(1), matched.group(2)
    diameter = scalars.get(f"boss_{idx}_d")
    height = scalars.get(f"boss_{idx}_h")
    if suffix == "draft_deg" and diameter is not None and height is not None and height > 0:
        tip = diameter / 2.0 - height * math.tan(math.radians(value))
        if tip <= 0.05:
            raise GeometryError(
                f"{name}={format_number(value)} closes the boss "
                f"(tip radius {format_number(tip)} mm)"
            )
    if suffix in ("chamfer", "chamfer_w") and diameter is not None and value >= diameter / 2.0:
        raise GeometryError(f"{name}={format_number(value)} is at least the boss radius")
    if suffix in ("chamfer", "chamfer_h") and height is not None and value >= height:
        raise GeometryError(f"{name}={format_number(value)} is at least the boss height")


def _check_features(scalars: dict[str, float]) -> None:
    if all(k in scalars for k in ("fillet_r", "leg_x", "leg_y", "base_x", "base_y")):
        leg_x, leg_y = scalars["leg_x"], scalars["leg_y"]
        base_x, base_y = scalars["base_x"], scalars["base_y"]
        if leg_x >= base_x - 1e-9:
            raise GeometryError(
                f"leg_x={format_number(leg_x)} is at least base_x "
                f"({format_number(base_x)} mm), so the upright is not an L"
            )
        if leg_y >= base_y - 1e-9:
            raise GeometryError(
                f"leg_y={format_number(leg_y)} is at least base_y "
                f"({format_number(base_y)} mm), so the foot is not an L"
            )
        # A fillet on both ends of an edge needs the edge longer than 2r.
        # The short edges are the two thicknesses and the two inner walls.
        limit = min(leg_x, leg_y, base_x - leg_x, base_y - leg_y) / 2.0
        if scalars["fillet_r"] >= limit - 1e-9:
            raise GeometryError(
                f"fillet_r={format_number(scalars['fillet_r'])} is at least half the shortest "
                f"edge of the bracket ({format_number(limit)} mm), so the vertical rounds meet"
            )
    if "fillet_r" in scalars and "base_x" in scalars and "base_y" in scalars:
        limit = min(scalars["base_x"], scalars["base_y"]) / 2.0
        if scalars["fillet_r"] >= limit - 1e-9:
            raise GeometryError(
                f"fillet_r={format_number(scalars['fillet_r'])} is at least half the short side "
                f"of the base ({format_number(limit)} mm), so the rounded rectangle collapses"
            )
    if "edge_fillet_r" in scalars and all(k in scalars for k in ("base_x", "base_y", "base_t")):
        limit = min(scalars["base_x"], scalars["base_y"], scalars["base_t"]) / 2.0
        if scalars["edge_fillet_r"] >= limit - 1e-9:
            raise GeometryError(
                f"edge_fillet_r={format_number(scalars['edge_fillet_r'])} is at least half the "
                f"smallest side of the base ({format_number(limit)} mm), so the filleted box collapses"
            )
    for name, value in scalars.items():
        matched = _HOLE_D.fullmatch(name)
        if not matched:
            continue
        idx = matched.group(1)
        for other, label in ((f"hole_{idx}_cbore_d", "counterbore"), (f"hole_{idx}_csk_d", "countersink")):
            if other in scalars and value >= scalars[other] - 1e-9:
                raise GeometryError(
                    f"{name}={format_number(value)} is not smaller than its {label} "
                    f"{other}={format_number(scalars[other])}"
                )
    for name, value in scalars.items():
        matched = re.fullmatch(r"hole_(\d+)_(floor_r|rim_r|bot_rim_r)", name)
        if not matched:
            continue
        idx, kind = matched.group(1), matched.group(2)
        if kind == "floor_r":
            depth = scalars.get(f"hole_{idx}_depth")
            diam = scalars.get(f"hole_{idx}_d")
            if depth is not None and value >= depth - 1e-9:
                raise GeometryError(
                    f"{name}={format_number(value)} is at least the blind depth "
                    f"({format_number(depth)} mm)"
                )
            if diam is not None and value >= diam / 2.0 - 1e-9:
                raise GeometryError(
                    f"{name}={format_number(value)} is at least the hole radius "
                    f"({format_number(diam / 2.0)} mm)"
                )
        else:
            thick = scalars.get("base_t")
            if thick is not None and value >= thick - 1e-9:
                raise GeometryError(
                    f"{name}={format_number(value)} is at least the base thickness "
                    f"({format_number(thick)} mm)"
                )


def _check_holes(scalars, notes, solids, mode: str) -> None:
    indices = sorted({m.group(1) for name in scalars if (m := _HOLE_D.fullmatch(name))})
    for idx in indices:
        axis = _hole_axis(idx, scalars, notes)
        if axis is None:
            continue
        uv = _hole_uv(idx, axis, scalars)
        if uv is None:
            continue
        diameter = scalars[f"hole_{idx}_d"]
        _require_fit(f"hole_{idx}_d", diameter / 2.0, axis, uv, solids, mode)
        if f"hole_{idx}_cbore_d" in scalars:
            _require_fit(f"hole_{idx}_cbore_d", scalars[f"hole_{idx}_cbore_d"] / 2.0, axis, uv, solids, mode)
        if f"hole_{idx}_csk_d" in scalars:
            _require_fit(f"hole_{idx}_csk_d", scalars[f"hole_{idx}_csk_d"] / 2.0, axis, uv, solids, mode)
        chamfer = scalars.get(f"hole_{idx}_chamfer")
        if chamfer is not None and chamfer > 0:
            _require_fit(f"hole_{idx}_d", diameter / 2.0 + chamfer, axis, uv, solids, mode,
                         label=f"hole_{idx}_d with its chamfer")
        for key in (f"hole_{idx}_rim_r", f"hole_{idx}_bot_rim_r"):
            extra = scalars.get(key)
            if extra is not None and extra > 0:
                _require_fit(key, diameter / 2.0 + extra, axis, uv, solids, mode,
                             label=f"{key} past the hole wall")
    for name, value in scalars.items():
        matched = _MEMBER_HOLE_D.fullmatch(name)
        if not matched:
            continue
        prefix = f"{matched.group(1)}_{matched.group(2)}"
        if f"{prefix}_x" not in scalars or f"{prefix}_y" not in scalars:
            continue
        _require_fit(name, value / 2.0, "Z", (scalars[f"{prefix}_x"], scalars[f"{prefix}_y"]),
                     solids, mode)


def _require_fit(name: str, radius: float, axis: str, uv, solids, mode: str, label: str | None = None) -> None:
    u, v = uv
    shown = label or name
    diameter = radius * 2.0
    shorter = _shorter_side(solids, mode, axis, u, v)
    # Slack on the rim must not let a hole through that is wider than the wall.
    if shorter is not None and diameter >= shorter - 0.05:
        raise GeometryError(
            f"{shown}={format_number(diameter)} does not fit: the hole is larger than the wall "
            f"it sits in ({format_number(shorter)} mm on the shorter side)"
        )
    if _circle_fits(solids, mode, axis, u, v, radius):
        return
    raise GeometryError(
        f"{shown}={format_number(diameter)} does not fit: the hole crosses the edge of the wall it sits in"
    )


def _hole_axis(idx: str, scalars: dict, notes: dict) -> str | None:
    matched = re.search(r"axis ([XYZ])", notes.get(f"hole_{idx}_d", ""))
    if matched:
        return matched.group(1)
    has = {c: f"hole_{idx}_{c}" in scalars for c in "xyz"}
    if has["y"] and has["z"] and not has["x"]:
        return "X"
    if has["x"] and has["z"] and not has["y"]:
        return "Y"
    if has["x"] and has["y"]:
        return "Z"
    return None


def _hole_uv(idx: str, axis: str, scalars: dict):
    keys = [f"hole_{idx}_{c}" for c in _FACE[axis]]
    if any(key not in scalars for key in keys):
        return None
    return scalars[keys[0]], scalars[keys[1]]


def _solids(script: Script, scalars: dict[str, float]) -> tuple[list[_Extrusion], str]:
    by = {p.name: p for p in script.parameters}
    if all(key in scalars for key in ("base_x", "base_y", "base_t", "base_cx", "base_cy", "base_z0")):
        return [_box(scalars)], "single"
    if all(key in scalars for key in (
            "base_x", "base_y", "base_t", "base_x0", "base_y0", "base_z0", "leg_x", "leg_y")):
        return [_bracket_solid(scalars, script.model)], "single"
    if ("extrude_len" in scalars and "outline" in by and _is_points(by["outline"].value)):
        axis = _axis_from_note(by["outline"].note) or "Z"
        return [_from_outline(axis, scalars.get("extrude_0", 0.0), scalars["extrude_len"], by["outline"].value)], "single"
    solids = []
    for name, length in scalars.items():
        matched = _EXTRUDE_LEN.fullmatch(name)
        if not matched:
            continue
        suffix = matched.group(1) + matched.group(2)
        outline = by.get(f"outline_{suffix}")
        if outline is None or not _is_points(outline.value):
            continue
        solids.append(_from_outline(
            matched.group(1).upper(), scalars.get(f"extrude_{suffix}_0", 0.0), length, outline.value,
        ))
    return solids, _combine_mode(script.model, len(solids))


def _is_points(value) -> bool:
    return isinstance(value, list) and bool(value) and isinstance(value[0], list)


def _bracket_signs(model: str) -> tuple[int, int]:
    """+1 or -1 for each leg, from the profile the script actually writes.

    A negative foot is ``-base_x`` in CadQuery and OpenSCAD, and
    ``base_x0 - base_x`` in FreeCAD. The same for ``base_y``.
    """
    sx = -1 if re.search(r"-\s*base_x\b", model) else 1
    sy = -1 if re.search(r"-\s*base_y\b", model) else 1
    return sx, sy


def _bracket_solid(scalars: dict[str, float], model: str) -> _Extrusion:
    """The sharp L, in world coordinates, so a mounting hole can be checked."""
    sx, sy = _bracket_signs(model)
    x0, y0 = scalars["base_x0"], scalars["base_y0"]
    base_x, base_y = scalars["base_x"], scalars["base_y"]
    leg_x, leg_y = scalars["leg_x"], scalars["leg_y"]
    local = (
        (0.0, 0.0),
        (base_x, 0.0),
        (base_x, leg_y),
        (leg_x, leg_y),
        (leg_x, base_y),
        (0.0, base_y),
    )
    if sx * sy < 0:
        local = tuple(reversed(local))
    outline = [[x0 + sx * u, y0 + sy * v] for u, v in local]
    return _Extrusion("Z", scalars["base_z0"], scalars["base_t"], outline, "xy")


def _box(scalars: dict[str, float]) -> _Extrusion:
    cx, cy = scalars["base_cx"], scalars["base_cy"]
    x, y, z0, thick = scalars["base_x"], scalars["base_y"], scalars["base_z0"], scalars["base_t"]
    outline = [
        [cx - x / 2.0, cy - y / 2.0],
        [cx + x / 2.0, cy - y / 2.0],
        [cx + x / 2.0, cy + y / 2.0],
        [cx - x / 2.0, cy + y / 2.0],
    ]
    return _Extrusion("Z", z0, thick, outline, "xy")


def _from_outline(axis: str, origin: float, length: float, outline) -> _Extrusion:
    return _Extrusion(axis, float(origin), float(length), outline, _FACE[axis])


def _axis_from_note(note: str) -> str | None:
    matched = re.search(r"\b(XY|XZ|YZ)\b", note)
    if not matched:
        return None
    return _PLANE_AXIS[matched.group(1)]


def _combine_mode(model: str, count: int) -> str:
    if count <= 1:
        return "single"
    if ".intersect(" in model or "intersection()" in model or ".common(" in model:
        return "intersect"
    return "union"


def _span_of(solid: _Extrusion, world_axis: str) -> tuple[float, float]:
    if world_axis == solid.axis.lower():
        return solid.origin, solid.origin + solid.length
    index = solid.plane.index(world_axis)
    vals = [float(point[index]) for point in solid.outline]
    return min(vals), max(vals)


def _contains(solid: _Extrusion, hole_axis: str, u: float, v: float, slack: float = 0.0) -> bool:
    if solid.axis == hole_axis:
        return _inside(solid.outline, u, v, slack)
    face = _FACE[hole_axis]
    ulo, uhi = _span_of(solid, face[0])
    vlo, vhi = _span_of(solid, face[1])
    return ulo - slack <= u <= uhi + slack and vlo - slack <= v <= vhi + slack


def _inside(poly, x: float, y: float, slack: float) -> bool:
    # A point within ``slack`` of the polygon counts as inside, so a fitted
    # hole that kisses a chord is not refused. The sample ring still catches
    # a circle that leaves the wall.
    if _ray_inside(poly, x, y):
        return True
    if slack <= 0:
        return False
    return _point_segment_distance(x, y, poly) <= slack


def _ray_inside(poly, x: float, y: float) -> bool:
    inside = False
    j = len(poly) - 1
    for i, point in enumerate(poly):
        xi, yi = point
        xj, yj = poly[j]
        if (yi > y) != (yj > y):
            cross = (xj - xi) * (y - yi) / ((yj - yi) or 1e-30) + xi
            if x < cross:
                inside = not inside
        j = i
    return inside


def _point_segment_distance(x: float, y: float, poly) -> float:
    best = 1e9
    j = len(poly) - 1
    for i, point in enumerate(poly):
        xi, yi = point
        xj, yj = poly[j]
        dx, dy = xj - xi, yj - yi
        length2 = dx * dx + dy * dy
        t = 0.0 if length2 <= 1e-18 else max(0.0, min(1.0, ((x - xi) * dx + (y - yi) * dy) / length2))
        best = min(best, math.hypot(x - (xi + t * dx), y - (yi + t * dy)))
        j = i
    return best


def _samples(u: float, v: float, radius: float) -> list[tuple[float, float]]:
    points = [(u, v)]
    count = 48
    for k in range(count):
        angle = 2.0 * math.pi * k / count
        points.append((u + radius * math.cos(angle), v + radius * math.sin(angle)))
    return points


def _circle_fits(solids, mode: str, axis: str, u: float, v: float, radius: float) -> bool:
    def sample_ok(su: float, sv: float, slack: float) -> bool:
        flags = [_contains(solid, axis, su, sv, slack) for solid in solids]
        if mode == "intersect":
            return all(flags)
        return any(flags)

    # The centre has to lie in the material. The rim may graze a fitted edge.
    if not sample_ok(u, v, _BREAKOUT_MM):
        return False
    return all(sample_ok(su, sv, _BREAKOUT_MM) for su, sv in _samples(u, v, radius)[1:])


def _shorter_side(solids, mode: str, axis: str, u: float, v: float) -> float | None:
    rects = []
    face = _FACE[axis]
    for solid in solids:
        ulo, uhi = _span_of(solid, face[0])
        vlo, vhi = _span_of(solid, face[1])
        rects.append((ulo, uhi, vlo, vhi))
    if not rects:
        return None
    if mode == "intersect":
        ulo = max(item[0] for item in rects)
        uhi = min(item[1] for item in rects)
        vlo = max(item[2] for item in rects)
        vhi = min(item[3] for item in rects)
        if uhi <= ulo or vhi <= vlo:
            return 0.0
        return min(uhi - ulo, vhi - vlo)
    hosts = [item for item in rects if item[0] - _BREAKOUT_MM <= u <= item[1] + _BREAKOUT_MM
             and item[2] - _BREAKOUT_MM <= v <= item[3] + _BREAKOUT_MM]
    if not hosts:
        return 0.0
    return max(min(item[1] - item[0], item[3] - item[2]) for item in hosts)


def _backend_available(backend: str) -> bool:
    if backend == "cadquery":
        try:
            import cadquery  # noqa: F401
        except ImportError:
            return False
        return True
    if backend == "openscad":
        from .openscad_code import openscad_bin
        return openscad_bin() is not None
    if backend == "freecad":
        from .freecad_code import freecad_bin
        return freecad_bin() is not None
    return False


def _missing_backend(backend: str) -> str:
    if backend == "openscad":
        return "OpenSCAD is not on PATH, so the script was not rendered."
    if backend == "freecad":
        return "freecadcmd is not on PATH, so the macro was not rendered."
    return "cadquery is not installed, so the script was not rendered. Install it with pip install 'mesh2cad[cadquery]'."


def _default_render_path(path: str, backend: str) -> Path:
    file = Path(path)
    if backend == "openscad":
        return file.with_suffix(".stl")
    return file.with_suffix(".step")


def _check_suffix(backend: str, output_path: str) -> None:
    suffix = Path(output_path).suffix.lower()
    if backend == "openscad" and suffix != ".stl":
        raise ParamError(
            "OpenSCAD writes an STL mesh. Pass -o with a .stl file. Nothing was written."
        )
    if backend in ("cadquery", "freecad") and suffix not in (".step", ".stp", ".stl"):
        raise ParamError(
            f"{backend} writes .step or .stl, not {suffix or 'a file with no suffix'}. Nothing was written."
        )


def _export_kind(backend: str, dest: str | None) -> str | None:
    if dest is None:
        return None
    suffix = Path(dest).suffix.lower()
    if suffix == ".stl":
        return "stl"
    if suffix in (".step", ".stp"):
        return "step"
    return None


def _script_destination(path: str, in_place: bool, output_script: str | None) -> Path | None:
    if in_place and output_script:
        raise ParamError("pass only one of --in-place and --output-script")
    if in_place:
        return Path(path)
    if output_script:
        return Path(output_script)
    return None


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def _measure(code: str, backend: str, work: Path, export: str | None, what: str):
    work.mkdir(parents=True, exist_ok=True)
    try:
        if backend == "cadquery":
            return _measure_cadquery(code, work, export)
        if backend == "openscad":
            return _measure_openscad(code, work, export)
        if backend == "freecad":
            return _measure_freecad(code, work, export)
    except GeometryError:
        raise
    except Exception as exc:  # noqa: BLE001
        raise GeometryError(f"{what} did not produce a valid solid ({exc}). Nothing was written.") from exc
    raise GeometryError(f"unknown backend {backend}")


def _measure_cadquery(code: str, work: Path, export: str | None):
    import cadquery as cq

    namespace: dict = {"__name__": "mesh2cad_edit"}
    exec(compile(code, "<mesh2cad-cadquery>", "exec"), namespace)
    result = namespace.get("result")
    if result is None or not hasattr(result, "solids"):
        raise GeometryError("the script did not produce a CadQuery solid. Nothing was written.")
    solids = result.solids().vals()
    if len(solids) != 1:
        raise GeometryError(f"edit produced {len(solids)} solids, expected one. Nothing was written.")
    solid = solids[0]
    if not solid.isValid():
        raise GeometryError("edit produced a solid that is not valid. Nothing was written.")
    volume = float(solid.Volume())
    if volume <= 1e-6:
        raise GeometryError("edit produced an empty solid. Nothing was written.")
    box = solid.BoundingBox()
    metrics = {
        "volume": volume,
        "bbox_min": [float(box.xmin), float(box.ymin), float(box.zmin)],
        "bbox_max": [float(box.xmax), float(box.ymax), float(box.zmax)],
    }
    exported = None
    if export == "step":
        exported = work / "out.step"
        cq.exporters.export(result, str(exported))
    elif export == "stl":
        exported = work / "out.stl"
        cq.exporters.export(result, str(exported))
    return metrics, exported


def _metrics_from_mesh(mesh) -> dict:
    if mesh is None or len(getattr(mesh, "faces", [])) == 0:
        raise GeometryError("render produced an empty mesh. Nothing was written.")
    volume = abs(float(mesh.volume))
    if not mesh.is_watertight or volume <= 1e-6:
        raise GeometryError("render is not a closed solid. Nothing was written.")
    bounds = mesh.bounds
    return {
        "volume": volume,
        "bbox_min": [float(v) for v in bounds[0]],
        "bbox_max": [float(v) for v in bounds[1]],
    }


def _measure_openscad(code: str, work: Path, export: str | None):
    from .openscad_code import render_mesh

    if export == "step":
        raise GeometryError("OpenSCAD writes an STL mesh. Nothing was written.")
    mesh = render_mesh(code, work, timeout=180.0)
    metrics = _metrics_from_mesh(mesh)
    exported = work / "part.stl" if export == "stl" else None
    return metrics, exported


def _measure_freecad(code: str, work: Path, export: str | None):
    from .freecad_code import freecad_bin, render_mesh

    mesh = render_mesh(code, work, timeout=300.0)
    metrics = _metrics_from_mesh(mesh)
    if export == "stl":
        return metrics, work / "part.stl"
    if export == "step":
        dest = work / "out.step"
        _freecad_step(code, work, dest)
        return metrics, dest
    return metrics, None


def _freecad_step(code: str, work: Path, dest: Path) -> None:
    from .freecad_code import freecad_bin
    import subprocess

    binary = freecad_bin()
    if not binary:
        raise GeometryError("freecadcmd is not on PATH, so STEP was not written. Nothing was written.")
    macro = work / "export.FCMacro"
    driver = work / "export_step.py"
    macro.write_text(code, encoding="utf-8")
    driver.write_text(
        "MACRO = %r\nDEST = %r\n"
        "ns = {'__name__': 'mesh2cad_edit', '__file__': MACRO}\n"
        "with open(MACRO, encoding='utf-8') as handle:\n"
        "    exec(compile(handle.read(), MACRO, 'exec'), ns)\n"
        "shape = ns['result']\n"
        "solids = shape.Solids\n"
        "if len(solids) != 1:\n"
        "    raise RuntimeError('expected one solid, got %d' % len(solids))\n"
        "shape.exportStep(DEST)\n" % (str(macro), str(dest)),
        encoding="utf-8",
    )
    env = os.environ.copy()
    env.setdefault("QT_QPA_PLATFORM", "offscreen")
    proc = subprocess.run(
        [binary, str(driver)], capture_output=True, text=True, timeout=300, cwd=str(work), env=env,
    )
    if proc.returncode != 0 or not dest.is_file() or dest.stat().st_size == 0:
        tail = (proc.stderr or proc.stdout or "").strip().splitlines()
        detail = tail[-1] if tail else f"exit {proc.returncode}"
        raise GeometryError(f"freecadcmd did not write STEP ({detail}). Nothing was written.")
